#!/usr/bin/env bash
# Build the inventory of one environment from Terraform outputs (single source of truth).
#
#   ./gen-inventory.sh <dev|prod> [--mode bastion|public] [--force]
#
# Modes:
#   public   SSH to the servers' PUBLIC IPs. For the first run, before the private interface exists.
#            The host firewall/Scaleway must restrict SSH to your admin IPs (admin_cidrs).
#   bastion  (default) SSH to the PRIVATE IPs through the bastion (ProxyJump bastion@<gateway>:<port>).
#
# Writes (git-ignored):
#   inventories/<env>/hosts.yml
#   inventories/<env>/group_vars/all/terraform.yml
# Only non-sensitive outputs are read (never passwords or secret keys).
# Requires: python3, and the Terraform state of the environment (via ../terraform/tf.sh).
set -euo pipefail
cd "$(dirname "$0")"
usage() {
  echo "Usage: $0 <dev|prod> [--mode bastion|public] [--force]" >&2
  exit 1
}
[[ $# -ge 1 ]] || usage
env="$1"
shift
case "$env" in
  dev | prod) ;;
  *) echo "Unknown environment '$env' (expected dev or prod)." >&2; usage ;;
esac
mode=bastion
force=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --mode)
      [[ $# -ge 2 ]] || usage
      mode="$2"
      shift 2
      ;;
    --force)
      force=1
      shift
      ;;
    *) usage ;;
  esac
done
case "$mode" in
  bastion | public) ;;
  *) echo "Unknown mode '$mode' (expected bastion or public)." >&2; usage ;;
esac
hosts_file="inventories/${env}/hosts.yml"
tf_vars_file="inventories/${env}/group_vars/all/terraform.yml"
if [[ $force -eq 0 && ( -e "$hosts_file" || -e "$tf_vars_file" ) ]]; then
  echo "$hosts_file or $tf_vars_file already exists. Use --force to overwrite." >&2
  exit 1
fi
outputs="$(../terraform/tf.sh "$env" output -json)"
mkdir -p "inventories/${env}/group_vars/all"
OUTPUTS="$outputs" ENV_NAME="$env" MODE="$mode" HOSTS_FILE="$hosts_file" TF_VARS_FILE="$tf_vars_file" python3 - <<'PY'
import json
import os
import sys

env = os.environ["ENV_NAME"]
mode = os.environ["MODE"]
out = json.loads(os.environ["OUTPUTS"])


def val(name):
    item = out.get(name)
    return item.get("value") if isinstance(item, dict) else None


def q(value):
    return json.dumps(value)  # JSON strings are valid YAML scalars


gw_ip = val("gateway_public_ip")
port = val("bastion_ssh_port") or 61000
cidr = val("private_network_cidr")
if not cidr:
    sys.exit("Output private_network_cidr is missing: run terraform apply with the updated outputs.tf.")
if mode == "bastion" and not gw_ip:
    sys.exit("Output gateway_public_ip is null: cannot use bastion mode.")

servers = {
    "app": {
        "private_ip": val("app_server_private_ip"),
        "public_ip": val("app_server_public_ipv4"),
        "vlan": val("app_server_private_vlan"),
    },
    "cartography": {
        "private_ip": val("cartography_server_private_ip"),
        "public_ip": val("cartography_server_public_ipv4"),
        "vlan": val("cartography_server_private_vlan"),
    },
}
key = "private_ip" if mode == "bastion" else "public_ip"
lines = [
    "---",
    f"# Generated by gen-inventory.sh ({mode} mode) from Terraform outputs. Do not edit; regenerate.",
    "all:",
    "  vars:",
    "    ansible_user: ubuntu",
    f"    connection_mode: {mode}",
    "  children:",
    "    servers:",
    "      children:",
]
found = 0
for group, data in servers.items():
    lines.append(f"        {group}:")
    if not data[key]:
        lines.append("          hosts: {}")
        print(f"warning: no {key} for {group} (server not created?). Group left empty.", file=sys.stderr)
        continue
    found += 1
    lines.append("          hosts:")
    lines.append(f"            {env}-{group}:")
    lines.append(f"              ansible_host: {q(data[key])}")
    if data["private_ip"]:
        lines.append(f"              private_ip: {q(data['private_ip'])}")
    if data["public_ip"]:
        lines.append(f"              public_ip: {q(data['public_ip'])}")
    if data["vlan"] is not None:
        lines.append(f"              private_vlan: {int(data['vlan'])}")
    if mode == "bastion":
        lines.append(f"              ansible_ssh_common_args: {q(f'-o ProxyJump=bastion@{gw_ip}:{port}')}")
if not found:
    sys.exit(f"No server has a {key} in the Terraform outputs. Are the servers created (create_*_server)?")
with open(os.environ["HOSTS_FILE"], "w", encoding="utf-8") as fh:
    fh.write("\n".join(lines) + "\n")

tf_lines = [
    "---",
    f"# Generated by gen-inventory.sh {env} from Terraform outputs (git-ignored). Regenerate instead of editing.",
    f"private_network_cidr: {q(cidr)}",
]
if gw_ip:
    tf_lines += [f"bastion_host: {q(gw_ip)}", f"bastion_port: {int(port)}"]
if val("backups_bucket_name"):
    tf_lines.append(f"backups_bucket_name: {q(val('backups_bucket_name'))}")
with open(os.environ["TF_VARS_FILE"], "w", encoding="utf-8") as fh:
    fh.write("\n".join(tf_lines) + "\n")
PY
echo "Wrote $hosts_file and $tf_vars_file (mode: $mode)." >&2
echo "Next: cp inventories/${env}/group_vars/all/main.yml.example inventories/${env}/group_vars/all/main.yml  (if not done), then edit." >&2
